create policy admin_promoitems on promo_items    for all to authenticated using (true) with check (true);
create policy admin_clientes   on clientes       for all to authenticated using (true) with check (true);
create policy admin_usuarios   on usuarios       for all to authenticated using (true) with check (true);
create policy admin_pedidos    on pedidos        for all to authenticated using (true) with check (true);
