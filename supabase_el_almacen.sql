-- ============================ CATÁLOGOS =====================================
create table categorias (
  id text primary key, nombre text not null, emoji text, color text, orden int default 0
);
create table formas_pago (
  id text primary key, nombre text not null, emoji text, orden int default 0
);
create table tipos_envio (
  id text primary key, nombre text not null, descripcion text,
  costo numeric(12,2) default 0, emoji text, pide_dir boolean default false, orden int default 0
);
create table estados_pedido (
  id text primary key, nombre text not null, color text, orden int default 0
);

-- ============================ PRODUCTOS =====================================
create table productos (
  id           text primary key,
  nombre       text not null,
  categoria_id text references categorias(id) on delete set null,
  precio       numeric(12,2) not null default 0,
  unidad       text not null default 'un' check (unidad in ('kg','un','doc')),
  emoji        text,
  descripcion  text,
  activo       boolean default true,
  orden        int default 0,
  created_at   timestamptz default now()
);
create index idx_productos_cat on productos(categoria_id);
create index idx_productos_activo on productos(activo);

-- ============================ PROMOS ========================================
create table promos (
  id text primary key, nombre text not null, emoji text, descripcion text,
  precio numeric(12,2) not null default 0, activo boolean default true, orden int default 0
);
create table promo_items (
  promo_id    text references promos(id) on delete cascade,
  producto_id text references productos(id) on delete cascade,
  cantidad    numeric(12,3) not null default 1,
  primary key (promo_id, producto_id)
);

-- ============================ CLIENTES ======================================
create table clientes (
  id         text primary key default gen_random_uuid()::text,
  nombre     text not null,
  tel        text,
  dir        text,
  email      text,
  nota       text,
  created_at timestamptz default now()
);
create index idx_clientes_tel on clientes(tel);

-- ============================ USUARIOS DEL PANEL ============================
-- NOTA: para producción real conviene Supabase Auth (ver README). Esta tabla
-- replica el login simple de la app (demo). La contraseña NO debería quedar
-- en texto plano en un sistema real.
create table usuarios (
  id         text primary key default gen_random_uuid()::text,
  usuario    text unique not null,
  pass       text not null,
  nombre     text,
  rol        text not null default 'cliente' check (rol in ('admin','empleado','cliente')),
  tel        text,
  created_at timestamptz default now()
);

-- ============================ PEDIDOS =======================================
create table pedidos (
  n              bigint generated by default as identity primary key,
  ts             timestamptz default now(),
  cliente_nombre text,
  cliente_tel    text,
  cliente_dir    text,
  tipo           text references tipos_envio(id),
  pago           text references formas_pago(id),
  estado         text references estados_pedido(id),
  nota           text,
  envio_costo    numeric(12,2) default 0,
  total          numeric(12,2) default 0
);
create index idx_pedidos_estado on pedidos(estado);
create index idx_pedidos_tel on pedidos(cliente_tel);
create index idx_pedidos_ts on pedidos(ts desc);

create table pedido_items (
  id          bigint generated by default as identity primary key,
  pedido_n    bigint references pedidos(n) on delete cascade,
  producto_id text,                 -- id de producto o de promo (referencia suave)
  nombre      text not null,        -- snapshot al momento del pedido
  unidad      text default 'un',
  precio      numeric(12,2) not null,
  qty         numeric(12,3) not null,
  es_promo    boolean default false
);
create index idx_pitems_pedido on pedido_items(pedido_n);

-- ============================ updated_at (config) ===========================
create or replace function touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger trg_config_updated before update on config
  for each row execute function touch_updated_at();

-- ============================================================================
--  RPC: crear_pedido  (para que la tienda pública cree pedidos de forma segura,
--  sin exponer las tablas de pedidos/clientes a escritura anónima directa)
-- ============================================================================
create or replace function crear_pedido(
  p_nombre text, p_tel text, p_dir text,
  p_tipo text, p_pago text, p_nota text,
  p_items jsonb           -- [{producto_id,nombre,unidad,precio,qty,es_promo}]
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_n bigint; v_estado text; v_envio numeric := 0; v_total numeric := 0; it jsonb;
begin
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'El pedido no tiene items';
  end if;
  select id into v_estado from estados_pedido order by orden asc, id asc limit 1;
  select coalesce(costo,0) into v_envio from tipos_envio where id = p_tipo;
  select coalesce(sum((i->>'precio')::numeric * (i->>'qty')::numeric),0)
    into v_total from jsonb_array_elements(p_items) i;
  v_total := v_total + coalesce(v_envio,0);

  insert into pedidos(cliente_nombre,cliente_tel,cliente_dir,tipo,pago,estado,nota,envio_costo,total)
  values (p_nombre,p_tel,p_dir,p_tipo,p_pago,v_estado,p_nota,coalesce(v_envio,0),v_total)
  returning n into v_n;

  for it in select * from jsonb_array_elements(p_items) loop
    insert into pedido_items(pedido_n,producto_id,nombre,unidad,precio,qty,es_promo)
    values (v_n, it->>'producto_id', it->>'nombre', coalesce(it->>'unidad','un'),
            (it->>'precio')::numeric, (it->>'qty')::numeric,
            coalesce((it->>'es_promo')::boolean,false));
  end loop;

  if p_tel is not null and length(trim(p_tel)) > 0 then
    if exists (select 1 from clientes where tel = p_tel) then
      update clientes set nombre = coalesce(nullif(p_nombre,''), nombre),
                          dir    = coalesce(nullif(p_dir,''), dir)
        where tel = p_tel;
    else
      insert into clientes(nombre,tel,dir) values (p_nombre,p_tel,p_dir);
    end if;
  end if;
  return v_n;
end $$;

-- ============================================================================
--  RLS (Row Level Security)
--  Público (anon): lee catálogo/config y crea pedidos SOLO vía crear_pedido().
--  Staff (authenticated, vía Supabase Auth): gestiona todo.
-- ============================================================================
alter table config          enable row level security;
alter table categorias      enable row level security;
alter table formas_pago     enable row level security;
alter table tipos_envio     enable row level security;
alter table estados_pedido  enable row level security;
alter table productos       enable row level security;
alter table promos          enable row level security;
alter table promo_items     enable row level security;
alter table clientes        enable row level security;
alter table usuarios        enable row level security;
alter table pedidos         enable row level security;
alter table pedido_items    enable row level security;

